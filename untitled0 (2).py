@torch.no_grad()
def validate(
    eval_model
):

    eval_model.eval()


    total_loss = 0.0

    correct = 0

    total = 0


    for videos, labels in tqdm(

        val_loader,

        desc="Validation",

        leave=False

    ):

        videos = videos.to(

            DEVICE,

            non_blocking=True

        )


        labels = labels.to(

            DEVICE,

            non_blocking=True

        )


        # --------------------------------------------------------
        # Validation TTA
        # Original + temporal reverse + horizontal flip
        # --------------------------------------------------------

        val_views = [
            videos,
            torch.flip(videos, dims=[2]),
            torch.flip(videos, dims=[4])
        ]


        outputs_sum = None


        with torch.amp.autocast(

            "cuda",

            enabled=use_amp

        ):

            for view in val_views:

                view_outputs = eval_model(
                    view
                )


                if outputs_sum is None:

                    outputs_sum = view_outputs

                else:

                    outputs_sum += view_outputs


            outputs = (

                outputs_sum
                /
                len(val_views)

            )


            loss = criterion(

                outputs,

                labels

            )


        total_loss += (

            loss.item()

            *

            labels.size(0)

        )


        pred = outputs.argmax(
            dim=1
        )


        correct += (

            pred == labels

        ).sum().item()


        total += labels.size(0)


    return (

        total_loss
        /
        max(
            1,
            total
        ),

        correct
        /
        max(
            1,
            total
        )

    )


