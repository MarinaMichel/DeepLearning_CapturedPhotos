def mixup_batch(
    x,
    y,
    alpha=MIXUP_ALPHA
):

    if alpha <= 0:

        return (
            x,
            y,
            y,
            1.0
        )


    lam = float(

        np.random.beta(
            alpha,
            alpha
        )

    )


    index = torch.randperm(

        x.size(0),

        device=x.device

    )


    mixed_x = (

        lam * x

        +

        (1 - lam)
        * x[index]

    )


    return (

        mixed_x,

        y,

        y[index],

        lam

    )


def mixup_loss(
    criterion,
    outputs,
    y_a,
    y_b,
    lam
):

    return (

        lam

        *

        criterion(
            outputs,
            y_a
        )

        +

        (1 - lam)

        *

        criterion(
            outputs,
            y_b
        )

    )


