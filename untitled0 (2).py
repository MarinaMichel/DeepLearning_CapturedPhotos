def load_video(
    path,
    train=False,
    start_override=None
):

    total_frames, vr = (
        _get_reader_and_length(
            path
        )
    )


    if total_frames <= 0:

        return torch.zeros(
            3,
            NUM_FRAMES,
            IMG_SIZE,
            IMG_SIZE
        )


    # ========================================================
    # Temporal Sampling
    # ========================================================

    if (
        start_override is not None
        and total_frames > NUM_FRAMES
    ):

        start = min(
            start_override,
            total_frames - NUM_FRAMES
        )


        indices = np.linspace(

            start,

            start + NUM_FRAMES - 1,

            NUM_FRAMES

        ).astype(int)


    elif (
        train
        and total_frames > NUM_FRAMES
    ):

        max_start = (
            total_frames
            - NUM_FRAMES
        )


        start = random.randint(
            0,
            max_start
        )


        indices = np.linspace(

            start,

            start + NUM_FRAMES - 1,

            NUM_FRAMES

        ).astype(int)


    else:

        # For validation/test
        # sample uniformly across entire video

        indices = np.linspace(

            0,

            total_frames - 1,

            NUM_FRAMES

        ).astype(int)


    indices = np.clip(

        indices,

        0,

        total_frames - 1

    )


    # ========================================================
    # Read Frames
    # ========================================================

    raw_frames = None


    if vr is not None:

        try:

            raw_frames = (

                vr.get_batch(
                    indices
                ).asnumpy()

            )

        except Exception:

            raw_frames = None


    if raw_frames is None:

        raw_frames = _read_frames_cv2(

            path,

            indices

        )


    frames = raw_frames


    # ========================================================
    # Augmentation
    # ========================================================

    if train:

        frames = augment_clip(
            frames
        )

    else:

        frames = np.stack([

            cv2.resize(
                f,
                (
                    IMG_SIZE,
                    IMG_SIZE
                )
            )

            for f in frames

        ])


    # ========================================================
    # Normalize
    # ========================================================

    frames = frames.astype(
        np.float32
    )


    frames /= 255.0


    frames = (
        frames - MEAN
    ) / STD


    # ========================================================
    # T,H,W,C -> C,T,H,W
    # ========================================================

    frames = np.transpose(

        frames,

        (
            3,
            0,
            1,
            2
        )

    )


    return torch.tensor(

        frames,

        dtype=torch.float32

    )


