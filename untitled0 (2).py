class ModelEma:

    def __init__(
        self,
        model,
        decay=EMA_DECAY
    ):

        self.ema = copy.deepcopy(
            model
        ).eval()


        for p in self.ema.parameters():

            p.requires_grad_(False)


        self.decay = decay

        self.updates = 0


    @torch.no_grad()
    def update(
        self,
        model
    ):

        self.updates += 1


        d = min(

            self.decay,

            (
                self.updates + 1
            )
            /
            (
                self.updates + 10
            )

        )


        model_state = (
            model.state_dict()
        )


        for k, v in self.ema.state_dict().items():

            if v.dtype.is_floating_point:

                v.copy_(

                    v * d

                    +

                    (
                        1 - d
                    )

                    *

                    model_state[
                        k
                    ].detach()

                )

            else:

                v.copy_(
                    model_state[k]
                )


ema = ModelEma(
    model
)


