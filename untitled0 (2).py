@torch.no_grad()
def predict_probs_tta(

    video_path,

    n_clips=TTA_CLIPS

):

    total_frames, _ = (

        _get_reader_and_length(

            video_path

        )

    )


    # --------------------------------------------------------
    # Select multiple temporal clips
    # --------------------------------------------------------

    if (

        total_frames > NUM_FRAMES

        and

        n_clips > 1

    ):

        starts = np.linspace(

            0,

            max(

                1,

                total_frames
                -
                NUM_FRAMES

            ),

            n_clips

        ).astype(int)


    else:

        starts = [0]


    probs_sum = None


    # ========================================================
    # Predict every clip
    # ========================================================

    for start in starts:

        clip = load_video(

            video_path,

            train=False,

            start_override=int(
                start
            )

        )


        clip = clip.unsqueeze(
            0
        ).to(

            DEVICE,

            non_blocking=True

        )


        with torch.amp.autocast(

            "cuda",

            enabled=use_amp

        ):

            output = eval_model(

                clip

            )


        probs = torch.softmax(

            output.float(),

            dim=1

        )


        if probs_sum is None:

            probs_sum = probs

        else:

            probs_sum += probs


    # Average predictions
    return (

        probs_sum
        /
        len(starts)

    ).squeeze(0)


