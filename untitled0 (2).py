def _read_frames_cv2(
    path,
    indices
):

    cap = cv2.VideoCapture(
        path
    )

    frames = []


    for idx in indices:

        cap.set(
            cv2.CAP_PROP_POS_FRAMES,
            int(idx)
        )

        ret, frame = cap.read()


        if not ret:

            frame = np.zeros(
                (
                    IMG_SIZE,
                    IMG_SIZE,
                    3
                ),
                dtype=np.uint8
            )

        else:

            frame = cv2.cvtColor(
                frame,
                cv2.COLOR_BGR2RGB
            )


        frames.append(
            frame
        )


    cap.release()


    return np.asarray(
        frames
    )


