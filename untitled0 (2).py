class WLASLDataset(
    Dataset
):

    def __init__(
        self,
        records,
        class_to_idx,
        train=False
    ):

        self.records = records

        self.class_to_idx = class_to_idx

        self.train = train


    def __len__(self):

        return len(
            self.records
        )


    def __getitem__(
        self,
        index
    ):

        record = self.records[
            index
        ]


        video = load_video(

            record["video_path"],

            train=self.train

        )


        label = self.class_to_idx[

            record["gloss"]

        ]


        return (

            video,

            torch.tensor(
                label,
                dtype=torch.long
            )

        )


