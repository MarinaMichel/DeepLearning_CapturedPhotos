def train_epoch():

    model.train()


    total_loss = 0.0

    correct = 0

    total = 0


    pbar = tqdm(

        train_loader,

        desc="Training"

    )


    for videos, labels in pbar:

        videos = videos.to(

            DEVICE,

            non_blocking=True

        )


        labels = labels.to(

            DEVICE,

            non_blocking=True

        )


        # ----------------------------------------------------
        # Mixup disabled
        # ----------------------------------------------------

        do_mixup = (

            MIXUP_ALPHA > 0

            and random.random()
            < MIXUP_PROB

        )


        if do_mixup:

            videos, y_a, y_b, lam = (

                mixup_batch(

                    videos,

                    labels

                )

            )


        optimizer.zero_grad(

            set_to_none=True

        )


        # ----------------------------------------------------
        # Forward
        # ----------------------------------------------------

        with torch.amp.autocast(

            "cuda",

            enabled=use_amp

        ):

            outputs = model(
                videos
            )


            if do_mixup:

                loss = mixup_loss(

                    criterion,

                    outputs,

                    y_a,

                    y_b,

                    lam

                )

            else:

                loss = criterion(

                    outputs,

                    labels

                )


        # ----------------------------------------------------
        # Backward
        # ----------------------------------------------------

        scaler.scale(
            loss
        ).backward()


        scaler.unscale_(
            optimizer
        )


        torch.nn.utils.clip_grad_norm_(

            model.parameters(),

            1.0

        )


        scaler.step(
            optimizer
        )


        scaler.update()


        # ----------------------------------------------------
        # EMA
        # ----------------------------------------------------

        ema.update(
            model
        )


        # ----------------------------------------------------
        # Metrics
        # ----------------------------------------------------

        total_loss += (

            loss.item()

            *

            labels.size(0)

        )


        pred = outputs.argmax(
            dim=1
        )


        correct += (

            pred == labels

        ).sum().item()


        total += labels.size(0)


        pbar.set_postfix(

            loss=f"{loss.item():.3f}",

            acc=f"{correct / max(total, 1) * 100:.2f}%"

        )


    return (

        total_loss
        /
        max(
            1,
            total
        ),

        correct
        /
        max(
            1,
            total
        )

    )


