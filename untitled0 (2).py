def augment_clip(
    frames
):

    h, w, _ = frames[0].shape


    # --------------------------------------------------------
    # Random spatial crop
    # --------------------------------------------------------

    if random.random() < 0.8:

        scale = random.uniform(
            0.80,
            1.0
        )


        crop_h = max(
            int(h * scale),
            1
        )


        crop_w = max(
            int(w * scale),
            1
        )


        if (
            crop_h <= h
            and crop_w <= w
        ):

            y0 = random.randint(
                0,
                h - crop_h
            )


            x0 = random.randint(
                0,
                w - crop_w
            )


            frames = np.stack([

                cv2.resize(
                    f[
                        y0:y0 + crop_h,
                        x0:x0 + crop_w
                    ],

                    (
                        IMG_SIZE,
                        IMG_SIZE
                    )
                )

                for f in frames
            ])


        else:

            frames = np.stack([

                cv2.resize(
                    f,
                    (
                        IMG_SIZE,
                        IMG_SIZE
                    )
                )

                for f in frames
            ])


    else:

        frames = np.stack([

            cv2.resize(
                f,
                (
                    IMG_SIZE,
                    IMG_SIZE
                )
            )

            for f in frames
        ])


    # --------------------------------------------------------
    # Brightness / Contrast
    # Same transformation across whole video
    # --------------------------------------------------------

    if random.random() < 0.5:

        brightness = random.uniform(
            0.85,
            1.15
        )


        contrast = random.uniform(
            0.85,
            1.15
        )


        frames = frames.astype(
            np.float32
        )


        mean = frames.mean(
            axis=(1, 2),
            keepdims=True
        )


        frames = (
            (frames - mean)
            * contrast
            + mean
        )


        frames *= brightness


    return np.clip(
        frames,
        0,
        255
    )


